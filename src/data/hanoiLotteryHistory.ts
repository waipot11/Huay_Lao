  const meta = DAY_META[dt.getUTCDay()] || DAY_META[1];
  const fourDigits = fiveDigits.slice(-4);
  const threeDigitsTop = fiveDigits.slice(-3);
  const twoDigitsTop = fiveDigits.slice(-2);

